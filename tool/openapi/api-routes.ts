//
//   npm run openapi          regenerate docs/reference/openapi/
//   npm run openapi:check    fail when a committed document has drifted
//
// One entry per route the server maps, in path order. What each field means
// is `Route` in render-openapi.ts; a shape is a type name from the client's
// models.ts or wire-types.ts, a primitive, `{ key?: shape }` or `[shape]`.
// Three checks hold this table to the server:
// - OpenApiDocumentTests (backend/tests/Insolvia.Api.Tests) fails when a
//   route, its principal or its permissions differ from what the server maps;
// - the contract suite (contract/src/support/openapi.ts) checks every request
//   it sends and every answer it gets against the document;
// - `npm run openapi:check` fails when the committed JSON is stale.

