type Schema = { [key: string]: unknown };

const PRIMITIVES: Readonly<Record<string, Schema>> = {
  string: { type: 'string' },
  integer: { type: 'integer' },
  number: { type: 'number' },
  boolean: { type: 'boolean' },
  object: { type: 'object' },
  any: {},
};

function repoRoot(): string {
  return join(dirname(fileURLToPath(import.meta.url)), '..');
}

/** Turns the clients' TypeScript types into JSON Schema components. */
class SchemaBuilder {
  readonly components: Record<string, Schema> = {};
  readonly #checker: ts.TypeChecker;
  readonly #named = new Map<string, ts.Declaration>();
  readonly #byDeclaration = new Map<ts.Declaration, string>();

  constructor(program: ts.Program, sources: readonly string[]) {
    this.#checker = program.getTypeChecker();
    for (const source of sources) {
      const file = program.getSourceFile(source);
      if (!file) throw new Error(`${source} is not in the program`);
      for (const statement of file.statements) {
        if (!ts.isInterfaceDeclaration(statement) && !ts.isTypeAliasDeclaration(statement))
          continue;
        if (!statement.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
        // A generic type has no one shape; wire-types.ts names its instances.
        if (statement.typeParameters) continue;
        const name = statement.name.text;
        if (this.#named.has(name)) continue;
        this.#named.set(name, statement);
        this.#byDeclaration.set(statement, name);
      }
    }
  }

  /** A `$ref` to the named type, rendering its component on first use. */
  ref(name: string): Schema {
    const declaration = this.#named.get(name);
    if (!declaration) throw new Error(`no exported type named ${name} in this service's sources`);
    if (!(name in this.components)) {
      this.components[name] = {}; // reserve first: a type may refer to itself
      const type = this.#checker.getTypeAtLocation(
        (declaration as ts.InterfaceDeclaration | ts.TypeAliasDeclaration).name,
      );
      const schema = this.#structure(type);
      const description = this.#doc(declaration);
      this.components[name] = description ? { description, ...schema } : schema;
    }
    return { $ref: `#/components/schemas/${name}` };
  }

  /** A route-table shape, as JSON Schema. */
  shape(shape: Shape): Schema {
    if (typeof shape === 'string') return this.#word(shape);
    if (Array.isArray(shape)) return { type: 'array', items: this.shape(shape[0] as Shape) };
    const properties: Record<string, Schema> = {};
    const required: string[] = [];
    for (const [key, value] of Object.entries(shape as Record<string, Shape>)) {
      const optional = key.endsWith('?');
      const name = optional ? key.slice(0, -1) : key;
      properties[name] = this.shape(value);
      if (!optional) required.push(name);
    }
    return { type: 'object', properties, ...(required.length ? { required } : {}) };
  }

  #word(word: string): Schema {
    const parts = word.split('|');
    if (parts.length > 1 && parts.every((p) => p.startsWith("'"))) {
      return { type: 'string', enum: parts.map((p) => p.slice(1, -1)) };
    }
    if (parts.length === 2 && parts[1] === 'null') {
      return { anyOf: [this.#word(parts[0] as string), { type: 'null' }] };
    }
    return PRIMITIVES[word] ?? this.ref(word);
  }

  #doc(node: ts.Declaration): string {
    const symbol = (node as { symbol?: ts.Symbol }).symbol;
    return symbol
      ? clean(ts.displayPartsToString(symbol.getDocumentationComment(this.#checker)))
      : '';
  }

  /** The schema for `type`: a `$ref` when it is a named type, else its structure. */
  #schema(type: ts.Type): Schema {
    const declaration = (type.aliasSymbol ?? type.getSymbol())?.declarations?.[0];
    const named = declaration && this.#byDeclaration.get(declaration);
    // An alias reached through its own name, or an interface itself — not an
    // instantiation of a generic one, nor a member type that merely shares a symbol.
    if (
      named &&
      (type.aliasSymbol ? !type.aliasTypeArguments : type === this.#declaredType(declaration))
    ) {
      return this.ref(named);
    }
    return this.#structure(type);
  }

  #declaredType(declaration: ts.Declaration): ts.Type | undefined {
    return ts.isInterfaceDeclaration(declaration)
      ? this.#checker.getTypeAtLocation(declaration.name)
      : undefined;
  }

  #structure(type: ts.Type): Schema {
    const checker = this.#checker;
    const flags = type.flags;
    if (flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) return {};
    if (flags & ts.TypeFlags.String) return { type: 'string' };
    if (flags & ts.TypeFlags.Number) return { type: 'number' };
    if (flags & (ts.TypeFlags.Boolean | ts.TypeFlags.BooleanLiteral)) return { type: 'boolean' };
    if (flags & ts.TypeFlags.Null) return { type: 'null' };
    if (type.isStringLiteral()) return { type: 'string', const: type.value };
    if (type.isNumberLiteral()) return { type: 'integer', const: type.value };

    if (type.isUnion()) {
      const members = type.types.filter((t) => !(t.flags & ts.TypeFlags.Undefined));
      const isNull = (t: ts.Type) => (t.flags & ts.TypeFlags.Null) !== 0;
      const values = members.filter((t) => !isNull(t));
      const nullable = values.length < members.length;
      let schema: Schema;
      if (values.length > 0 && values.every((t) => t.isStringLiteral())) {
        schema = { type: 'string', enum: values.map((t) => (t as ts.StringLiteralType).value) };
      } else if (values.length > 0 && values.every((t) => t.isNumberLiteral())) {
        schema = { type: 'integer', enum: values.map((t) => (t as ts.NumberLiteralType).value) };
      } else if (values.every((t) => t.flags & ts.TypeFlags.BooleanLiteral)) {
        schema = { type: 'boolean' };
      } else if (values.length === 1) {
        schema = this.#schema(values[0] as ts.Type);
      } else {
        schema = { anyOf: values.map((t) => this.#schema(t)) };
      }
      return nullable ? { anyOf: [schema, { type: 'null' }] } : schema;
    }

    if (checker.isArrayType(type) || checker.isTupleType(type)) {
      const [element] = checker.getTypeArguments(type as ts.TypeReference);
      return { type: 'array', items: element ? this.#schema(element) : {} };
    }

    const properties: Record<string, Schema> = {};
    const required: string[] = [];
    for (const property of checker.getPropertiesOfType(type)) {
      const declaration = property.valueDeclaration ?? property.declarations?.[0];
      const propertyType = declaration
        ? checker.getTypeOfSymbolAtLocation(property, declaration)
        : checker.getTypeOfSymbol(property);
      if (propertyType.getCallSignatures().length > 0) continue;
      const schema = this.#schema(propertyType);
      const description = clean(ts.displayPartsToString(property.getDocumentationComment(checker)));
      properties[property.name] = description ? { description, ...schema } : schema;
      if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name);
    }
    const index = checker.getIndexInfoOfType(type, ts.IndexKind.String);
    return {
      type: 'object',
      ...(Object.keys(properties).length ? { properties } : {}),
      ...(required.length ? { required } : {}),
      ...(index ? { additionalProperties: this.#schema(index.type) } : {}),
    };
  }
}

/**
 * Doc-comment text, with `{@link X}` turned into code and each paragraph's
 * hard wraps joined (a list item or quote keeps its line).
 */
function clean(text: string): string {
  return text
    .replace(/([^\n])\n(?![\n\-*>|]|\d+\.)/g, '$1 ')
    .replace(
      /\{@link(?:code|plain)?\s+([^}\s|]+)(?:\s*\|\s*|\s+)?([^}]*)\}/g,
      (_, target: string, label: string) => (label.trim() ? label.trim() : `\`${target}\``),
    )
    .trim();
}

/** The doc comment of each method of `className`, by method name. */
function methodDocs(program: ts.Program, file: string, className: string): Map<string, string> {
  const docs = new Map<string, string>();
  const source = program.getSourceFile(file);
  if (!source) throw new Error(`${file} is not in the program`);
  const checker = program.getTypeChecker();
  for (const statement of source.statements) {
    if (!ts.isClassDeclaration(statement) || statement.name?.text !== className) continue;
    for (const member of statement.members) {
      if (!ts.isMethodDeclaration(member) || !ts.isIdentifier(member.name)) continue;
      const symbol = checker.getSymbolAtLocation(member.name);
      if (!symbol) continue;
      docs.set(member.name.text, ts.displayPartsToString(symbol.getDocumentationComment(checker)));
    }
  }
  return docs;
}

/**
 * Splits a client doc comment into summary and description. Its first line is
 * "`METHOD /path` — summary"; the route itself is dropped, since the document
 * already says it.
 */
function prose(doc: string): { summary: string; description: string } {
  const text = clean(doc);
  const [first = '', ...rest] = text.split(/\n\s*\n/);
  const line = first
    .replace(/^`[A-Z]+ [^`]+`\s*—\s*/, '')
    .replace(/\s+/g, ' ')
    .trim();
  const summary = line.charAt(0).toUpperCase() + line.slice(1);
  return { summary, description: rest.join('\n\n').trim() };
}

function tagOf(path: string): string {
  const words = path.split('/').filter((s) => s && s !== 'v1' && !s.startsWith('{'));
  return words.slice(0, 2).join(' ') || 'health';
}

function operationId(route: Route): string {
  return (
    route.method.toLowerCase() +
    route.path
      .split(/[/.-]/)
      .filter((s) => s && s !== 'v1')
      .map((s) => s.replace(/[{}]/g, ''))
      .map((s) => (s[0] ?? '').toUpperCase() + s.slice(1))
      .join('')
  );
}

function render(service: Service, program: ts.Program): object {
  const schemas = new SchemaBuilder(program, service.typeSources);
  const docs = service.client
    ? methodDocs(program, service.client.file, service.client.className)
    : new Map<string, string>();
  const paths: Record<string, Record<string, unknown>> = {};

  for (const route of service.routes) {
    const fromClient = route.call ? docs.get(route.call) : undefined;
    if (route.call && fromClient === undefined) {
      throw new Error(
        `${route.method} ${route.path}: ${service.client?.className} has no method ${route.call}`,
      );
    }
    const written = fromClient ? prose(fromClient) : { summary: '', description: '' };
    const summary = route.summary ?? written.summary;
    if (!summary) throw new Error(`${route.method} ${route.path} has no summary`);
    const description = [route.description ?? written.description]
      .concat(
        route.permissions?.length
          ? [`Requires ${route.permissions.map((p) => `\`${p}\``).join(' and ')}.`]
          : [],
      )
      .filter(Boolean)
      .join('\n\n');

    const parameters: unknown[] = [];
    for (const match of route.path.matchAll(/\{(\w+)\}/g)) {
      parameters.push({ name: match[1], in: 'path', required: true, schema: { type: 'string' } });
    }
    for (const [key, shape] of Object.entries(route.query ?? {})) {
      const optional = key.endsWith('?');
      parameters.push({
        name: optional ? key.slice(0, -1) : key,
        in: 'query',
        required: !optional,
        schema: schemas.shape(shape),
      });
    }

    const responses: Record<string, unknown> = {};
    for (const [status, shape] of Object.entries(route.responses)) {
      responses[status] =
        shape === null
          ? { description: 'No content.' }
          : shape === 'ICS'
            ? {
                description: 'An iCalendar feed.',
                content: { 'text/calendar': { schema: { type: 'string' } } },
              }
            : {
                description: 'OK.',
                content: { 'application/json': { schema: schemas.shape(shape) } },
              };
    }
    responses['4XX'] = { $ref: '#/components/responses/Error' };

    const security =
      route.auth === 'none'
        ? []
        : route.path === '/v1/me/calendar.ics'
          ? [{ calendarToken: [] }, { staff: [] }]
          : [{ [route.auth]: [] }];

    paths[route.path] ??= {};
    paths[route.path]![route.method.toLowerCase()] = {
      operationId: route.call ?? operationId(route),
      tags: [tagOf(route.path)],
      summary,
      ...(description ? { description } : {}),
      security,
      ...(route.permissions?.length ? { 'x-insolvia-permissions': route.permissions } : {}),
      ...(parameters.length ? { parameters } : {}),
      ...(route.body !== undefined
        ? {
            requestBody: {
              required: true,
              content: { 'application/json': { schema: schemas.shape(route.body) } },
            },
          }
        : {}),
      responses,
    };
  }

  const used = new Set<string>(service.routes.flatMap((r) => (r.auth === 'none' ? [] : [r.auth])));
  if (service.routes.some((r) => r.path === '/v1/me/calendar.ics')) used.add('calendarToken');
  return {
    openapi: '3.1.0',
    info: { title: service.title, version: '1', description: service.description },
    servers: [{ url: service.server, description: 'Local (docker compose up)' }],
    paths,
    components: {
      schemas: Object.fromEntries(
        Object.entries(schemas.components).sort(([a], [b]) => a.localeCompare(b)),
      ),
      responses: {
        Error: {
          description: 'A refusal, in the shared error envelope.',
          content: {
            'application/json': {
              schema: {
                type: 'object',
                properties: {
                  error: {
                    type: 'string',
                    description: 'A stable code: `ValidationError`, `NotFound`, …',
                  },
                  message: { type: 'string' },
                  fields: {
                    type: 'object',
                    additionalProperties: { type: 'string' },
                    description: 'Per-field messages, on a 400 that names fields.',
                  },
                },
                required: ['error'],
              },
            },
          },
        },
      },
      securitySchemes: Object.fromEntries(
        Object.entries(SECURITY_SCHEMES).filter(([name]) => used.has(name)),
      ),
    },
  };
}

async function main(args: string[]): Promise<void> {
  const check = args.includes('--check');
  const root = repoRoot();
  process.chdir(root);
  const program = ts.createProgram([API_MODELS, API_CLIENT, ADMIN_CLIENT, WIRE_TYPES], {
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    allowImportingTsExtensions: true,
    exactOptionalPropertyTypes: true,
    strict: true,
    noEmit: true,
  });
  const prettier = await resolveConfig(join(root, 'docs/reference/openapi/api.json'));

  const drifted: string[] = [];
  for (const service of SERVICES) {
    const rendered = await format(JSON.stringify(render(service, program)), {
      ...prettier,
      parser: 'json',
    });
    const file = join(root, service.file);
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // absent: rendered below, or reported as drifted under --check
    }
    if (current === rendered) continue;
    if (check) {
      drifted.push(service.file);
      continue;
    }
    writeFileSync(file, rendered);
    process.stdout.write(`wrote ${service.file}\n`);
  }

  if (drifted.length === 0) {
    if (check) process.stdout.write('OpenAPI documents are current.\n');
    return;
  }
  process.stderr.write(
    `These OpenAPI documents are stale:\n\n${drifted.map((f) => `  ${f}`).join('\n')}\n\n` +
      `Run \`${REGEN_COMMAND}\` and commit the result.\n`,
  );
  process.exit(1);
}

await main(process.argv.slice(2));
