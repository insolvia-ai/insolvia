/**
 * A shape in a route table: a type name (`'Case'`), a primitive (`'string'`,
 * `'integer'`, `'number'`, `'boolean'`, `'object'` for any JSON object), a
 * union of literals (`"'requested'|'waived'"`), either of those `|null`, an
 * object whose optional keys end in `?`, or `[shape]` for an array.
 */
export type Shape = string | { readonly [key: string]: Shape } | readonly [Shape];

export interface Route {
  readonly method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';
  /** The server's route template, parameters and all. */
  readonly path: string;
  /** The client method that calls it; its doc comment is the description. */
  readonly call?: string;
  /**
   * Who may call it: `staff` (a firm user's token), `client` (a debtor's
   * portal token), `google` (a staff member's Google ID token, admin service
   * only) or `none`.
   */
  readonly auth: 'staff' | 'client' | 'google' | 'none';
  /** Each `<feature>:<level>` the caller's firm role must hold. */
  readonly permissions?: readonly string[];
  /** Query parameters; a key ending in `?` is optional. */
  readonly query?: { readonly [name: string]: Shape };
  readonly body?: Shape;
  /** Each success status and its body; `null` for none, `'ICS'` for a calendar. */
  readonly responses: { readonly [status: number]: Shape | null };
  /** Overrides the client's first line; required when there is no `call`. */
  readonly summary?: string;
  readonly description?: string;
}

interface Service {
  readonly file: string;
  readonly title: string;
  readonly description: string;
  readonly server: string;
  readonly routes: readonly Route[];
  /** Where named types are looked up, first match wins. */
  readonly typeSources: readonly string[];
  /** The client whose method doc comments describe the routes. */
  readonly client?: { readonly file: string; readonly className: string };
}

