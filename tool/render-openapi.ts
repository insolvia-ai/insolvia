// Renders the OpenAPI documents for the backend's HTTP services:
//
//   docs/reference/openapi/api.json     the API (backend/src/Insolvia.Api)
//   docs/reference/openapi/admin.json   the admin service (backend/src/Insolvia.Admin)
//
//   npm run openapi
//   npm run openapi:check
//
// `--check` renders in memory and exits non-zero if a committed document has
// drifted, the same contract as render-brand-theme.ts.
//
// ── Where each part comes from ──────────────────────────────────────────────
//
// - The routes: one table per service (openapi/api-routes.ts,
//   openapi/admin-routes.ts) — method, path, principal, permissions, body,
//   query and answers.
// - The schemas: the clients' own TypeScript types (the API client's
//   models.ts, the admin client's client.ts), plus openapi/wire-types.ts for
//   the few wire shapes no client names. Those types already mirror the wire
//   field for field, with doc comments, and the contract suite proves the
//   clients against the running hosts — a second hand-written copy of every
//   shape would be the thing that drifts.
// - The prose: each route's client method's doc comment, whose first line is
//   "`GET /v1/...` — what it does".
//
// The .NET hosts do not describe their own routes: they write their JSON by
// hand (FlaskJson, ADR 0028), so ASP.NET's generator would see no request or
// response types. Instead, three checks hold these documents to the server —
// OpenApiDocumentTests in each host's test project (every route, principal and
// permission), the contract suite (every exchange it makes, against the
// schemas), and `openapi:check` (the committed JSON is current).
//
// The MCP server is not here: it speaks JSON-RPC, not REST, and
// docs/reference/mcp-surface.md is its reference.

